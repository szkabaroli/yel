//! Copied from ark's `ark-language-server/src/main.rs` — the file, not the
//! idea: same stack (`lsp-server` + `lsp-types`, no async runtime), same
//! crossbeam `select!` event loop over the connection and a threadpool, same
//! `MainLoopTask` shapes, same stale-diagnostics clearing via
//! `files_with_errors`. Deviations, each forced and declared:
//!
//! - **Projects are directories.** Ark walks for `ark-project.json` naming a
//!   `main` file; yel's package *is* a directory (`plans/modules.md` §4), so
//!   `find_projects` looks for `yel-project.json` first and otherwise treats
//!   any workspace directory containing `.yel` files as a project.
//! - **Compilation is `yelc_hir::check_package`** (ark: `check_program`) with
//!   the open buffers overlaid — ark recompiles from disk on save; overlays
//!   let diagnostics track unsaved edits.
//! - **Nothing non-`Send` crosses threads.** Ark ships `Arc<ast::File>`
//!   between workers; yel's trees are cheap to reparse, so workers parse from
//!   the content they are handed and only paths, strings and diagnostics
//!   travel.

use crossbeam::channel::{Receiver, Sender};
use crossbeam::select;
use lsp_server::{Connection, Message, Notification};
use lsp_types::notification::{self, Notification as _};
use lsp_types::request::{self, Request};
